"""Matters: what a document MEANS.

The documents service stores paper and finds it again, and says so - the
case a document belongs to, the deadline it creates, the claim it proves
are "the consuming application's business". This is that application.

Built from a real case. A Medicaid renewal arrived as a seven-page scan
with an eight-day deadline, and reading it against the ledger split into
three piles that are the whole design:

* Already known - both pensions and the social security cheque were in
  the register, monthly, still arriving on the reporting date.
* Known but not provable - the county asked for GROSS income and the
  ledger only ever sees what landed after withholding; it asked for
  balances and the accounts held register sums, not statement balances.
* Not recorded anywhere - the incidental account at the facility, an
  annuity, a life policy, a vehicle.

Hence the principle everything here obeys: a fact is worth nothing
without its provenance. The same number means different things
depending on whether it came from a deposit, a statement or a benefit
letter, and only one of those is fit to put on a government form.
"""
