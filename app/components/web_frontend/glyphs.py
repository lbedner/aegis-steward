def category_glyph(category: str | None) -> str | None:
    """The path data for a category's glyph, or None when it has none."""
    if not category:
        return None
    icon = _BY_CATEGORY.get(category) or _BY_CATEGORY.get(
        category.split(":")[0].strip()
    )
    return _PATHS[icon] if icon else None


